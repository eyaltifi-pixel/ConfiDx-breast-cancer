#!/usr/bin/env python3
"""
Phase 4 - Niveau 3 : LLM-as-Judge (OBLIGATOIRE)
Objectif : un LLM externe (le "juge"), SANS accès à GUIDELINE_FACTS,
reçoit le rapport source + l'explication générée, et juge si l'explication
est cliniquement cohérente. Cela casse la circularité du Niveau 2 (qui
réutilise les mêmes règles injectées à l'entraînement).

Basé sur la Section 3.6.3 du document méthodologique (Phase 4, Niveau 3).

Plan d'échantillonnage : stratifié par sous-tâche (2=explication,
4=explication d'incertitude) et par condition (avec/sans guidelines).
Taille minimale calculée pour détecter un écart de 10 points de %
(p1=0.20, p2=0.10) avec puissance 80%, alpha=0.05.

NOTE IMPORTANTE : avec la formule exacte (arcsine, statsmodels), n ≈ 195
par bras (le document méthodologique indique n≈175, calcul probablement
fait avec une approximation normale simplifiée). Ce script utilise 195
par défaut mais le paramètre est ajustable -> a discuter avec le binome.

PREREQUIS : une clé API doit etre configurée (variable d'environnement
ANTHROPIC_API_KEY) pour que l'appel au juge fonctionne reellement.
Sans cle, le script s'execute quand meme en mode "dry-run" (affiche
l'echantillon et les prompts, sans appeler l'API).
"""

import json
import os
import random
from pathlib import Path
from collections import Counter

# ============================================================
# CONFIGURATION
# ============================================================

BASE_DIR = Path(__file__).parent.parent.parent
PROCESSED_DIR = BASE_DIR / "data" / "processed"
OUTPUT_DIR = BASE_DIR / "guidelines"
OUTPUT_DIR.mkdir(parents=True, exist_ok=True)

SEED = 42
random.seed(SEED)

N_PER_ARM = 195  # cf. note ci-dessus (methodologie indique ~175)
CALIBRATION_SAMPLE_SIZE = 60  # cas annotes aussi par 2 medecins (Cohen's kappa)

# ============================================================
# 1. PROMPT DU JUGE (SANS ACCES AUX GUIDELINE_FACTS)
# ============================================================

JUDGE_SYSTEM_PROMPT = """You are an independent medical expert evaluator. You will be given a
pathology report and a diagnostic explanation generated by an AI system.

Your task: judge whether the explanation is CLINICALLY CONSISTENT with the
report, using your own general medical knowledge only. Do NOT assume any
specific numeric thresholds beyond standard, well-established oncology
practice knowledge.

Respond ONLY in this exact JSON format, nothing else:
{
  "consistent": true or false,
  "confidence": a number from 0 to 1,
  "reasoning": "one or two sentences explaining your judgment"
}"""

def build_judge_user_prompt(source_report, generated_explanation):
    return f"""PATHOLOGY REPORT:
{source_report}

GENERATED EXPLANATION:
{generated_explanation}

Is the generated explanation clinically consistent with the report?"""

# ============================================================
# 2. CHARGEMENT ET ECHANTILLONNAGE STRATIFIE
# ============================================================

def load_json(path):
    with open(path, "r", encoding="utf-8") as f:
        return json.load(f)

def build_stratified_sample(split_name="test", n_per_arm=N_PER_ARM):
    """
    Construit un echantillon stratifie par sous-tache (2 et 4) et par
    condition (avec/sans guidelines, detectee via la presence du mot
    'Guidelines' dans le champ instruction).
    """
    sample = []

    for task_num in [2, 4]:
        path = PROCESSED_DIR / split_name / f"task{task_num}_{split_name}.json"
        if not path.exists():
            print(f"  ATTENTION : {path} introuvable, sous-tache {task_num} ignoree")
            continue

        data = load_json(path)

        with_guidelines = [
            ex for ex in data
            if "guideline" in ex.get("instruction", "").lower()
        ]
        without_guidelines = [
            ex for ex in data
            if "guideline" not in ex.get("instruction", "").lower()
        ]

        for condition_name, pool in [
            ("with_guidelines", with_guidelines),
            ("without_guidelines", without_guidelines),
        ]:
            n_take = min(n_per_arm, len(pool))
            if n_take < n_per_arm:
                print(
                    f"  ATTENTION : task{task_num}/{condition_name} n'a que "
                    f"{len(pool)} cas disponibles (< {n_per_arm} demandes)"
                )
            chosen = random.sample(pool, n_take) if pool else []
            for ex in chosen:
                sample.append({
                    "patient_id": ex.get("patient_id"),
                    "task_num": task_num,
                    "condition": condition_name,
                    "input": ex.get("input", ""),
                    "output": ex.get("output", ""),
                })

    return sample

# ============================================================
# 3. APPEL AU LLM JUGE (Anthropic API)
# ============================================================

def call_llm_judge(source_report, generated_explanation):
    """
    Appelle l'API Anthropic pour juger la coherence clinique.
    Necessite la variable d'environnement ANTHROPIC_API_KEY.
    Retourne un dict {consistent, confidence, reasoning} ou None si erreur.
    """
    api_key = os.environ.get("ANTHROPIC_API_KEY")
    if not api_key:
        return None  # mode dry-run : pas de cle configuree

    try:
        import anthropic
    except ImportError:
        print("  ERREUR : le package 'anthropic' n'est pas installe.")
        print("  Installe-le avec : pip install anthropic")
        return None

    client = anthropic.Anthropic(api_key=api_key)
    user_prompt = build_judge_user_prompt(source_report, generated_explanation)

    try:
        response = client.messages.create(
            model="claude-sonnet-4-5",
            max_tokens=300,
            system=JUDGE_SYSTEM_PROMPT,
            messages=[{"role": "user", "content": user_prompt}],
        )
        text = response.content[0].text.strip()
        text = text.replace("```json", "").replace("```", "").strip()
        return json.loads(text)
    except Exception as e:
        print(f"  ERREUR appel API : {e}")
        return None

# ============================================================
# 4. EXECUTION SUR L'ECHANTILLON
# ============================================================

def run_level3_judging(sample, dry_run=True):
    """
    Applique le juge LLM sur chaque element de l'echantillon.
    En mode dry_run=True, ne fait aucun appel API (juste pour verifier
    que l'echantillon est bien construit avant de depenser des credits API).
    """
    results = []
    for i, item in enumerate(sample):
        if dry_run:
            judgment = {"consistent": None, "confidence": None,
                        "reasoning": "DRY-RUN (pas d'appel API effectue)"}
        else:
            judgment = call_llm_judge(item["input"], item["output"])
            if judgment is None:
                judgment = {"consistent": None, "confidence": None,
                            "reasoning": "ERREUR ou cle API manquante"}
            if (i + 1) % 20 == 0:
                print(f"  ... {i + 1}/{len(sample)} cas juges")

        results.append({
            "patient_id": item["patient_id"],
            "task_num": item["task_num"],
            "condition": item["condition"],
            "judgment": judgment,
        })

    return results

# ============================================================
# 5. RAPPORT GLOBAL
# ============================================================

def summarize(results):
    total = len(results)
    judged = [r for r in results if r["judgment"]["consistent"] is not None]
    n_inconsistent = sum(1 for r in judged if r["judgment"]["consistent"] is False)

    by_condition = Counter()
    for r in judged:
        if r["judgment"]["consistent"] is False:
            by_condition[r["condition"]] += 1

    rate = (n_inconsistent / len(judged) * 100) if judged else None

    return {
        "total_sampled": total,
        "total_judged": len(judged),
        "n_inconsistent_level3": n_inconsistent,
        "hallucination_rate_level3_pct": round(rate, 2) if rate is not None else None,
        "inconsistent_by_condition": dict(by_condition),
    }

# ============================================================
# 6. MAIN
# ============================================================

def main():
    print("=" * 60)
    print("PHASE 4 - NIVEAU 3 : LLM-AS-JUDGE")
    print("=" * 60)

    print(f"\nTaille cible par bras : {N_PER_ARM}")
    print("Construction de l'echantillon stratifie (task 2/4 x avec/sans guidelines)...")
    sample = build_stratified_sample(split_name="test", n_per_arm=N_PER_ARM)
    print(f"\nEchantillon total construit : {len(sample)} cas")

    breakdown = Counter((s["task_num"], s["condition"]) for s in sample)
    for key, count in sorted(breakdown.items()):
        print(f"  Task {key[0]}, {key[1]} : {count} cas")

    has_api_key = bool(os.environ.get("ANTHROPIC_API_KEY"))
    if not has_api_key:
        print("\nATTENTION : ANTHROPIC_API_KEY non definie.")
        print("Le script s'execute en mode DRY-RUN (aucun appel API reel).")
        print("Une fois ta cle API disponible, definis-la avec :")
        print("  export ANTHROPIC_API_KEY='ta_cle_ici'")
        print("puis relance ce script pour le jugement reel.\n")

    results = run_level3_judging(sample, dry_run=not has_api_key)
    summary = summarize(results)

    print("\n--- RESULTATS ---")
    print(f"Cas echantillonnes    : {summary['total_sampled']}")
    print(f"Cas juges (avec API)  : {summary['total_judged']}")
    if summary["hallucination_rate_level3_pct"] is not None:
        print(f"Taux hallucination N3 : {summary['hallucination_rate_level3_pct']}%")
        print(f"Detail par condition  : {summary['inconsistent_by_condition']}")

    output_path = OUTPUT_DIR / "phase4_level3_report.json"
    with open(output_path, "w", encoding="utf-8") as f:
        json.dump({
            "n_per_arm_target": N_PER_ARM,
            "calibration_sample_size": CALIBRATION_SAMPLE_SIZE,
            "dry_run": not has_api_key,
            "summary": summary,
            "details": results,
        }, f, indent=2, ensure_ascii=False)

    print(f"\nRapport sauvegarde : {output_path}")
    print("=" * 60)
    print("TERMINE")
    print("=" * 60)


if __name__ == "__main__":
    main()